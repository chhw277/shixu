const errors=[];
const modifier=process.platform==='darwin'?'Meta':'Control';
async function launch(){
 const app=await electron.launch({...(process.env.SHIXU_SMOKE_EXECUTABLE?{executablePath:process.env.SHIXU_SMOKE_EXECUTABLE,args:[]}:{args:['.']}),env:{...process.env,SHIXU_TEST_DATA_DIR:directory},timeout:30000});
 const page=await app.firstWindow();page.on('pageerror',e=>errors.push(e.message));
 await expect(page.locator('.main-area h1')).toBeVisible();
 return {app,page};
}
